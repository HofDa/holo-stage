function makeI18nMap(field, translations) {
  const out = {};
  for (const l of LANGS) out[l] = { [field]: translations[l] };
  return out;
}

function upgradeDemoI18n(story) {
  if (!story || typeof story !== 'object') return;
  if (!story.i18n && story.title === DEMO_I18N.title.en) {
    story.i18n = makeI18nMap('title', DEMO_I18N.title);
  }
  if (!Array.isArray(story.scenes)) return;
  for (const sc of story.scenes) {
    if (!sc || sc.i18n) continue;
    if (sc.type === 'chapter' && sc.caption === DEMO_I18N.chapter.caption.en) {
      sc.i18n = makeI18nMap('caption', DEMO_I18N.chapter.caption);
    } else if (sc.type === 'quiz' && sc.question === DEMO_I18N.quiz.question.en) {
      sc.i18n = {};
      for (const l of LANGS) {
        sc.i18n[l] = { question: DEMO_I18N.quiz.question[l], explain: DEMO_I18N.quiz.explain[l] };
      }
      if (Array.isArray(sc.answers)) {
        sc.answers.forEach((ans, idx) => {
          const d = DEMO_I18N.quiz.answers[idx];
          if (ans && !ans.i18n && d && ans.text === d.en) ans.i18n = makeI18nMap('text', d);
        });
      }
    } else if (sc.type === 'together' && sc.prompt === DEMO_I18N.together.prompt.en) {
      sc.i18n = makeI18nMap('prompt', DEMO_I18N.together.prompt);
    } else if (sc.type === 'turns' && sc.prompt === DEMO_I18N.turns.prompt.en) {
      sc.i18n = makeI18nMap('prompt', DEMO_I18N.turns.prompt);
    }
  }
}

