function detectLang() {
  const nav = (typeof navigator !== 'undefined' && (navigator.language || (navigator.languages && navigator.languages[0]))) || 'en';
  const code = String(nav).toLowerCase().slice(0, 2);
  return LANGS.includes(code) ? code : 'en';
}

