function t(key, vars = {}, lang = (typeof state !== 'undefined' && state?.lang) || 'en') {
  const dict = UI_STRINGS[lang] || UI_STRINGS.en;
  let str = dict[key] ?? UI_STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, String(v));
  return str;
}

function setLoc(obj, key, val, lang = (typeof state !== 'undefined' && state?.lang) || 'en') {
  if (!obj) return;
  obj.i18n ||= {};
  obj.i18n[lang] ||= {};
  obj.i18n[lang][key] = val;
  obj[key] = val;
}

function getLoc(obj, key, lang = (typeof state !== 'undefined' && state?.lang) || 'en', { fallback = true } = {}) {
  if (!obj) return '';
  const direct = obj.i18n?.[lang]?.[key];
  if (typeof direct === 'string' && (direct.trim() || !fallback)) return direct;
  if (!fallback) {
    const hasAny = LANGS.some(l => obj.i18n?.[l]?.[key] !== undefined);
    if (hasAny) return typeof direct === 'string' ? direct : '';
    return typeof obj[key] === 'string' ? obj[key] : '';
  }
  const order = [...new Set([lang, (typeof state !== 'undefined' && state?.lang) || 'en', 'en', 'de', 'it'])];
  for (const l of order) {
    const v = obj.i18n?.[l]?.[key];
    if (typeof v === 'string' && v.trim()) return v;
  }
  return typeof obj[key] === 'string' ? obj[key] : '';
}

function defaultPlayerName(n, lang = (typeof state !== 'undefined' && state?.lang) || 'en') {
  if (lang === 'de') return `Spieler ${n}`;
  if (lang === 'it') return `Giocatore ${n}`;
  return `Player ${n}`;
}

function displayPlayerName(cfg, idx, lang = (typeof state !== 'undefined' && state?.lang) || 'en') {
  const name = cfg?.name?.trim() || '';
  if (!name || /^(Player|Spieler|Giocatore)\s+[1-4]$/i.test(name)) return defaultPlayerName(idx + 1, lang);
  return cfg.name;
}

